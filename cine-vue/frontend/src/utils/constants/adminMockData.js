export function generateCinemaSeats(totalRows = 8, seatsPerRow = 14) {
    const seats = [];
    const rowLetters = ["A", "B", "C", "D", "E", "F", "G", "H", "J", "K"];

    for (let r = 0; r < totalRows; r++) {
        const row = rowLetters[r];
        for (let s = 1; s <= seatsPerRow; s++) {
            let type = "standard";
            let price = 110000;

            if (r >= 3 && r <= 6) {
                type = "vip";
                price = 135000;
            }

            if (r === totalRows - 1 && s % 2 === 1) {
                type = "couple";
                price = 260000;
            }

            let status = "available";
            const rand = Math.random();
            if (rand > 0.65) {
                status = "sold_cinehub";
            } else if (rand > 0.4) {
                status = "sold_partner";
            } else if (rand > 0.35) {
                status = "holding";
            }

            seats.push({
                id: `${row}-${s.toString().padStart(2, "0")}`,
                row,
                number: s,
                type,
                price,
                status,
                holdExpiresInSeconds:
                    status === "holding" ? Math.floor(Math.random() * 450) + 60 : undefined,
            });
        }
    }

    return seats;
}

